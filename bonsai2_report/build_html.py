#!/usr/bin/env python3
"""build_html.py: BONSAI2_TERNARY_FULL_REPORT.md -> one self-contained HTML file.
Every diagram is inlined as SVG, so the output has no external dependencies."""
import os, re
import markdown

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "BONSAI2_TERNARY_FULL_REPORT.md")
OUT = os.path.join(HERE, "BONSAI2_TERNARY_FULL_REPORT.html")

md = markdown.Markdown(extensions=["tables", "fenced_code", "toc", "sane_lists"],
                       extension_configs={"toc": {"toc_depth": "2-3"}})
body = md.convert(open(SRC, encoding="utf-8").read())
toc = md.toc


def inline_svg(m):
    alt, path = m.group(2), m.group(1)
    svg = open(os.path.join(HERE, path), encoding="utf-8").read()
    svg = re.sub(r"<defs>.*?</defs>", "", svg, flags=re.S)  # unused markers; avoids duplicate ids
    svg = re.sub(r'\swidth="\d+"\sheight="\d+"', "", svg, count=1)  # scale with the page via viewBox
    svg = svg.replace("<svg ", f'<svg role="img" aria-label="{alt}" ', 1)
    name = os.path.basename(path)
    return f'<figure class="diagram">{svg}<figcaption>{name}</figcaption></figure>'


# markdown renders ![alt](src) as <img alt="..." src="..." />, wrapped in <p>
body = re.sub(r'<p>\s*<img alt="([^"]*)" src="(diagrams/[^"]+\.svg)"\s*/?>\s*</p>',
              lambda m: inline_svg(type("M", (), {"group": lambda self, i: (None, m.group(2), m.group(1))[i]})()), body)
# key-value tables written as "| | |" get an empty header row: drop it
body = re.sub(r"<thead>\s*<tr>(?:\s*<th[^>]*>\s*</th>)+\s*</tr>\s*</thead>", "", body)
# '---' right before a section heading duplicates the heading's own rule
body = re.sub(r"<hr\s*/?>\s*(?=<h2)", "", body)
body = body.replace("All 29 diagrams are in <code>diagrams/</code> and are generated by <code>make_diagrams.py</code> from the measured numbers.",
                    "All 29 diagrams are embedded in this file; they are generated by <code>make_diagrams.py</code> from the measured numbers.")
missing = re.findall(r'<img[^>]+diagrams/', body)
assert not missing, missing

title = re.search(r"<h1[^>]*>(.*?)</h1>", body).group(1)
css = """
:root { --ink:#1b1f24; --muted:#6b7480; --line:#d9dde2; --accent:#2f6fb3; --bg:#ffffff; --soft:#f6f8fa; }
* { box-sizing: border-box; }
html { scroll-behavior: smooth; }
body { margin:0; font: 16px/1.6 "Segoe UI", Helvetica, Arial, sans-serif; color:var(--ink); background:var(--bg); }
.layout { display:flex; max-width:1500px; margin:0 auto; }
nav.toc { position:sticky; top:0; align-self:flex-start; width:290px; height:100vh; overflow:auto;
          padding:28px 18px; border-right:1px solid var(--line); background:var(--soft); font-size:13.5px; }
nav.toc .ttl { font-weight:600; margin-bottom:8px; color:var(--muted); text-transform:uppercase; letter-spacing:.05em; font-size:12px; }
nav.toc ul { list-style:none; padding-left:12px; margin:2px 0; }
nav.toc > ul { padding-left:0; }
nav.toc a { color:var(--ink); text-decoration:none; display:block; padding:2px 0; }
nav.toc a:hover { color:var(--accent); }
main { flex:1; min-width:0; padding:32px 48px 80px; max-width:1160px; }
h1 { font-size:30px; line-height:1.25; margin:0 0 12px; }
h2 { font-size:24px; margin-top:48px; padding-top:12px; border-top:2px solid var(--line); }
h3 { font-size:19px; margin-top:34px; }
h4 { font-size:16px; margin-top:26px; }
a { color:var(--accent); }
hr { border:none; border-top:1px solid var(--line); margin:36px 0; }
code { font-family: "SFMono-Regular", Consolas, "Liberation Mono", monospace; font-size:.88em;
       background:#eef1f4; padding:.1em .35em; border-radius:4px; }
pre { background:#f2f4f7; padding:12px 14px; border-radius:6px; overflow:auto; }
pre code { background:none; padding:0; }
table { border-collapse:collapse; width:100%; margin:16px 0; font-size:14.5px; display:block; overflow-x:auto; }
th, td { border:1px solid var(--line); padding:7px 10px; text-align:left; vertical-align:top; }
th { background:var(--soft); }
tr:nth-child(even) td { background:#fbfcfd; }
figure.diagram { margin:22px 0 28px; padding:10px; border:1px solid var(--line); border-radius:8px; background:#fff; }
figure.diagram svg { width:100%; height:auto; display:block; }
figcaption { font-size:12px; color:var(--muted); text-align:right; margin-top:4px; }
blockquote { margin:16px 0; padding:8px 16px; border-left:4px solid var(--accent); background:var(--soft); }
.meta { color:var(--muted); font-size:13px; margin-bottom:24px; }
@media (max-width: 1000px) { nav.toc { display:none; } main { padding:20px; } }
@media print {
  nav.toc { display:none; } main { padding:0; max-width:none; }
  figure.diagram { break-inside:avoid; border:none; } h2, h3 { break-after:avoid; }
  body { font-size:12pt; }
}
"""
html = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{re.sub('<[^>]+>', '', title)}</title>
<style>{css}</style>
</head>
<body>
<div class="layout">
<nav class="toc"><div class="ttl">Contents</div>{toc.replace('<div class="toc">', '').replace('</div>', '')}</nav>
<main>
{body}
<p class="meta">Self-contained HTML generated from BONSAI2_TERNARY_FULL_REPORT.md by build_html.py; all diagrams inlined as SVG.</p>
</main>
</div>
</body>
</html>
"""
open(OUT, "w", encoding="utf-8").write(html)
print(OUT, f"{os.path.getsize(OUT) / 1024:.0f} KiB", f"{html.count('<figure class=\"diagram\">')} diagrams inlined")
